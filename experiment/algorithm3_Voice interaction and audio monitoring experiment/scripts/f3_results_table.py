"""Function 3 results table, copied from the run folders' metrics.json by code (nothing typed by hand).

    python scripts/f3_results_table.py                 # print the table
    python scripts/f3_results_table.py --write         # replace the block between the markers in docs/results.md (section 3.4)
    python scripts/f3_results_table.py --check         # exit 1 when the block in docs/results.md is stale

Every row names its run folder, read from artifacts/experiments/. A run that is missing gives the row "run folder not present"; no number is ever filled in from memory,
and ``--write`` refuses to replace the committed table when no run has numbers. Rates carry their sample sizes; intervals are the ones saved in metrics.json.
"""

