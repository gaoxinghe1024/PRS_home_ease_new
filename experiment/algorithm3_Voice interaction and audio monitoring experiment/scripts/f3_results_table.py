BEGIN = "<!-- f3-results:begin (generated by scripts/f3_results_table.py; do not edit by hand) -->"
END = "<!-- f3-results:end -->"

# (id, what it measures). The run folder of each row is the NEWEST completed run of that experiment (see scripts/runs.py),
# so a re-run of the suite changes the table; the folder name is printed in every row.
RUNS: list[tuple[str, str]] = [
    ("A1", "VAD (speech branch gate)"),
    ("A2", "sound events, 3-class v1 and 4-class v2"),
    ("A2b", "deployable sound model, held-out fold"),
    ("A3", "reply intent, legacy protocol, Windows SAPI"),
    ("A3b", "reply intent, phrase bank, dev/test split"),
    ("A4", "speaker verification"),
    ("A5", "alarm behaviour (policy test)"),
    ("A6", "cancel-eligibility evidence, false-cancel rates"),
]


def pct(x: float, nd: int = 1) -> str:
    return f"{100.0 * x:.{nd}f}%"


def ci(v: list[float] | None, nd: int = 3) -> str:
    return "" if not v else f" [{v[0]:.{nd}f}, {v[1]:.{nd}f}]"


def pci(v: list[float] | None, nd: int = 1) -> str:
    return "" if not v else f" [{100.0 * v[0]:.{nd}f}, {100.0 * v[1]:.{nd}f}]"


def rate(d: dict[str, Any], nd: int = 2) -> str:
    return f"{pct(d['rate'], nd)} ({d['k']}/{d['n']})"


# ------------------------------------------------------------------ extractors: metrics dict -> list of (label, value)
def x_a2(m: dict[str, Any]) -> list[tuple[str, str]]:
    out = [("3-class macro-F1 (ESC-50 folds)", ", ".join(f"{e['config']} {e['macro_f1']:.3f}" for e in m["entries"]))]
    fc = m["four_class"]
    best = fc["best_by_cv_macro_f1"]
    c = fc["candidates"][best]
    rep = c["report"]
    h = rep["per_class"]["HELP"]
    out.append(("4-class best (pooled, mapping v2)", f"{best} macro-F1 {rep['macro_f1']:.3f}{ci(c['macro_f1_ci95_group_bootstrap'])} on {rep['n']} windows; per fold {min(f['macro_f1'] for f in c['per_fold']):.3f}-{max(f['macro_f1'] for f in c['per_fold']):.3f}"))
    out.append(("4-class other candidates", ", ".join(f"{k} {v['report']['macro_f1']:.3f}" for k, v in fc["candidates"].items() if k != best)))
    out.append(("HELP precision / recall", f"{h['precision']:.3f}{ci(h['precision_ci95'])} / {h['recall']:.3f}{ci(h['recall_ci95'])} (n HELP = {h['support']})"))
    for cls in ("IMPACT", "ABNORMAL", "DAILY"):
        p = rep["per_class"][cls]
        out.append((f"{cls} precision / recall", f"{p['precision']:.3f} / {p['recall']:.3f} (n = {p['support']})"))
    loco = fc["loco"]["runs"][best]
    out.append(("leave-one-corpus-out HELP recall", ", ".join(f"{k} held out {v['help_recall']:.3f}{ci(v['help_recall_ci95'])} (n = {v['help_support']})" for k, v in loco.items())))
    return out


def x_a2b(m: dict[str, Any]) -> list[tuple[str, str]]:
    t = m["test"]
    w = t["with_cutoffs"]
    h = w["per_class"]["HELP"]
    out = [
        ("candidate (chosen on dev)", f"{m['candidate']}, temperature {m['temperature']}"),
        ("cut-offs from dev (precision target %.2f)" % m["cutoffs"]["target_precision"], ", ".join(f"{k} {v['cutoff']:.2f}{'' if v['target_met'] else ' (target not met: ' + str(v['fallback']) + ')'}" for k, v in m["cutoffs"]["per_class"].items())),
        (f"test fold {t['fold']} ({t['n_windows']} windows, {t['groups']} groups)", f"macro-F1 {w['macro_f1']:.3f}{ci(t['macro_f1_ci95_group_bootstrap'])}, coverage {w['coverage']:.2f}, accuracy on accepted {w['accepted_accuracy']:.3f}"),
        ("HELP recall / precision", f"{h['recall']:.3f}{ci(h['recall_ci95'])} / {h['precision']:.3f}{ci(h['precision_ci95'])} (n HELP = {h['support']})"),
    ]
    for cls in ("DAILY", "ABNORMAL", "IMPACT"):
        p = w["per_class"][cls]
        out.append((f"{cls} precision / recall", f"{p['precision']:.3f} / {p['recall']:.3f} (n = {p['support']})"))
    return out


def x_a3(m: dict[str, Any]) -> list[tuple[str, str]]:
    n = m["entries"][0]["n"]
    return [(f"macro-F1 per configuration ({n} replies)", "; ".join(f"{e['config']} {e['macro_f1']:.3f} (ASR median {e['asr_latency_s_median']:.2f} s)" for e in m["entries"] if "macro_f1" in e))]


def x_a3b(m: dict[str, Any]) -> list[tuple[str, str]]:
    t = m["test"]
    grid = {(g["cfg"], g["method"]): g for g in t["grid"]}
    b, s = t["baseline"], t["selected"]
    plain = grid.get(("tiny|none|auto", "rule_v2"))
    out = [
        ("pre-change (tiny, plain, rule v1), TEST", f"macro-F1 {b['macro_f1']:.3f}{ci(b['macro_f1_ci'], 2)}, self calls for help missed {b['safety']['self_help_missed']}/{b['safety']['self_help_n']}"),
    ]
    if plain:
        out.append(("tiny, plain, rule v2 (product default), TEST", f"macro-F1 {plain['macro_f1']:.3f}, self HELP missed {plain['self_help_missed']}, TV/visitor read as REASSURANCE {plain['nonself_reassurance']}, ASR median {plain['asr_median_s']:.2f} s / p95 {plain['asr_p95_s']:.1f} s"))
    out.append((f"dev-selected cell ({s['cfg']} + {s['method']}), TEST", f"macro-F1 {s['macro_f1']:.3f}{ci(s['macro_f1_ci'], 2)}, self HELP missed {s['safety']['self_help_missed']}/{s['safety']['self_help_n']}, ASR p95 {s['latency_s']['p95']:.1f} s"))
    la = m["lexicon_audit"]
    out.append(("lexicon audit (rule v2 written with both splits in sight)", f"{len(la['only_test'])} of {la['n_cues_fired']} firing cues fire only on test wording; reference text macro-F1 {m['test']['text_ceiling']['rule_v2']:.3f}"))
    return out


def x_a5(m: dict[str, Any]) -> list[tuple[str, str]]:
    oc = m["outcomes"]
    closed = sum(1 for o in oc if o["closed_by_voice"])
    return [("policy", "PASSED" if m["policy_ok"] else "FAILED"), ("scripted outcomes", f"{len(oc)}; closed by a voice reply: {closed}; cancel_eligible = True in {sum(1 for o in oc if o['cancel_eligible'])}, event still EMERGENCY/OPEN in {sum(1 for o in oc if o['level_after'] == 'EMERGENCY' and o['status_after'] == 'OPEN')}")]


def _wilson(k: int, n: int, z: float = 1.959964) -> tuple[float, float]:
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    h = z * ((p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5)
    return max(0.0, (c - h) / d), min(1.0, (c + h) / d)


def x_a6(m: dict[str, Any]) -> list[tuple[str, str]]:
    sc = m["scenarios"]
    th = m["thresholds"]
    spk = m["speaker_layer"]
    at = spk["at_dev_thresholds"]["far_0.1pct"]
    out = [
        ("speakers / eval clips", f"{m['dev']['n_speakers']} dev + {m['eval_users']} disjoint eval synthetic speakers, {m['eval_clips']} eval clips"),
        ("thresholds from dev only", f"FAR 0.1% -> {th['far_0.1pct']:.3f}, FAR 1% -> {th['far_1pct']:.3f} ({m['reliability']['dev_impostor_trials']} dev impostor trials from {m['dev']['probes_with_enough_speech']} independent probes)"),
        ("eval speaker layer at the strict threshold", f"TAR {rate(at['tar'], 1)}{pci(at['tar']['wilson95'])}, FAR {rate(at['far'], 3)}{pci(at['far']['wilson95'], 3)} (trial-level interval, too narrow: speaker bootstrap in results.md 3.3); EER {spk['with_enough_speech']['eer']:.3f}"),
    ]
    names = {
        "true_cancel_clean": "enrolled speaker, reassurance (should be eligible)", "true_cancel_noise5dB": "same, 5 dB noise (should be eligible)", "other_person_same_words": "another person, same words",
        "other_person_noise5dB": "another person, same words, 5 dB noise", "visitor_on_behalf": "visitor answers on behalf", "tv_radio_speech": "TV / radio through the loudspeaker simulation",
        "replay_of_enrolled_voice": "enrolled user's recording replayed through the loudspeaker simulation", "enrolled_says_help": "enrolled speaker says a call for help", "household_noise_only": "household sounds only", "silence": "silence",
    }
    for k, label in names.items():
        s = sc.get(k)
        if not s:
            continue
        op = s["operating_points"]["far_0.1pct"]
        if k in ("household_noise_only", "silence") and s["trials"] != s["clips"]:  # one clip is tested against every enrolled user: the independent unit is the clip
            lo, hi = _wilson(op["k"], s["clips"])
            out.append((f"{label}", f"eligible {op['k']} of {s['clips']} clips [{100 * lo:.1f}, {100 * hi:.1f}%] ({s['trials']} trials = clips x users, not independent); words alone would cancel {rate(s['intent_only'], 1)}"))
            continue
        out.append((f"{label}", f"eligible {rate(op, 2)}{pci(op['wilson95'], 2)}; words alone would cancel {rate(s['intent_only'], 1)}"))
    return out


EXTRACT: dict[str, Callable[[dict[str, Any]], list[tuple[str, str]]]] = {"A2": x_a2, "A2b": x_a2b, "A3": x_a3, "A3b": x_a3b, "A5": x_a5, "A6": x_a6}


def load(folder: Path) -> dict[str, Any] | None:
    p = folder / "metrics.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.is_file() else None


def register_extra() -> None:
    """A1 and A4 extractors are registered by the Windows re-run section below (see x_a1 / x_a4)."""
    EXTRACT["A1"] = x_a1
    EXTRACT["A4"] = x_a4


def x_a1(m: dict[str, Any]) -> list[tuple[str, str]]:
    ent = m["entries"]
    allr = {e["config"]: e for e in ent if e["condition"] == "ALL"}
    out = [("frame precision / recall / F1, all conditions (%d frames)" % next(iter(allr.values()))["frames"], "; ".join(f"{k} {v['precision']:.3f} / {v['recall']:.3f} / {v['f1']:.3f}" for k, v in allr.items()))]
    gaps = {e["config"]: e for e in ent if e["condition"] == "impact_sounds_in_gaps"}
    out.append(("precision with impact sounds in the speech gaps", ", ".join(f"{k} {v['precision']:.3f}" for k, v in gaps.items())))
    return out


def x_a4(m: dict[str, Any]) -> list[tuple[str, str]]:
    ent = m["entries"]
    n = f"{ent[0]['genuine_trials_eval']} genuine / {ent[0]['impostor_trials_eval']} impostor eval trials, {m.get('eval_speakers')} eval speakers"
    out = [(f"EER by condition ({n})", "; ".join(f"{e['config'].split('_')[0]} {e['condition']} {e['eer_eval']:.3f}" for e in ent))]
    out.append(("TAR at the dev-chosen FAR 0.1% threshold, and the FAR that threshold gave on eval speakers (target 0.001)", "; ".join(
        f"{e['config'].split('_')[0]} {e['condition']} TAR {e['tar_at_dev_far0.1pct_threshold']:.3f} / FAR {e['far_eval_at_that_threshold']:.3f}" for e in ent)))
    out.append(("FAR 0.1% reliably estimable", "no (needs >= 10,000 impostor trials)" if not any(e["far_0.1pct_reliable"] for e in ent) else "partly"))
    return out


def render() -> tuple[str, dict[str, list[tuple[str, str]]]]:
    register_extra()
    lines = [BEGIN, "", "Copied by `scripts/f3_results_table.py` from the `metrics.json` of each run folder. Sample sizes are in the cells; intervals are the saved 95% ones. Clean, read, TTS or acted audio only.", "",
             "| ID | measures | run folder | status / code | numbers |", "|---|---|---|---|---|"]
    values: dict[str, list[tuple[str, str]]] = {}
    from runs import Runs

    runs = Runs()
    for rid, what in RUNS:
        f = runs.folder(rid)
        if f is None:
            lines.append(f"| {rid} | {what} | (none) | not present | run folder not present in this checkout: no numbers reported |")
            continue
        folder = f.name
        m = load(f)
        assert m is not None
        rows = EXTRACT[rid]({**m["metrics"], "_headline": m.get("headline", "")})
        values[rid] = rows
        prov = m.get("provenance", {})
        cell = "<br>".join(f"{a}: {b}" for a, b in rows).replace("|", "/")
        lines.append(f"| {rid} | {what} | `{folder}` | {m.get('status')} / `{prov.get('code_version')}` / {prov.get('versions', {}).get('platform', '?')} | {cell} |")
    lines += ["", END]
    return "\n".join(lines), values


def block_of(text: str) -> str | None:
    i, j = text.find(BEGIN), text.find(END)
    return text[i:j + len(END)] if 0 <= i < j else None


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    args = ap.parse_args()
    table, values = render()
    text = RESULTS.read_text(encoding="utf-8")
    if args.write:
        old = block_of(text)
        if old is None:
            print(f"markers not found in {RESULTS}", file=sys.stderr)
            return 2
        if not values:  # nothing to copy from: keep the committed table instead of replacing it with "not present" rows
            print("no run folder in artifacts/experiments has numbers: refusing to overwrite the table in docs/results.md", file=sys.stderr)
            return 3
        RESULTS.write_text(text.replace(old, table), encoding="utf-8")
        print(f"updated {RESULTS} ({len(values)} runs with numbers)")
        return 0
    if args.check:
        cur = block_of(text)
        if cur != table:
            print("docs/results.md is stale: run `python scripts/f3_results_table.py --write`", file=sys.stderr)
            return 1
        print("docs/results.md matches the run folders")
        return 0
    print(table)
    return 0


if __name__ == "__main__":
    sys.exit(main())
